function clampDay(monthKey: string, day: number): string {
  const [y, m] = monthKey.split('-').map(Number);
  const maxDay = new Date(y, m, 0).getDate();
  const safeDay = Math.min(day, maxDay);
  return `${monthKey}-${String(safeDay).padStart(2, '0')}`;
}

